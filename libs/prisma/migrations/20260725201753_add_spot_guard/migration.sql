ALTER TABLE "accounts" ADD CONSTRAINT "accounts_spot_automation_status_check"
    CHECK ("spotAutomationStatus" IN ('not_configured', 'pending', 'ready', 'error'));

ALTER TABLE "spot_guard_services" ADD CONSTRAINT "spot_guard_services_capacity_state_check"
    CHECK ("capacityState" IN ('spot', 'on_demand', 'mixed', 'unknown'));

ALTER TABLE "spot_guard_services" ADD CONSTRAINT "spot_guard_services_management_state_check"
    CHECK ("managementState" IN ('managed', 'unmanaged', 'opted_out'));

ALTER TABLE "spot_guard_services" ADD CONSTRAINT "spot_guard_services_service_status_check"
    CHECK ("serviceStatus" IS NULL OR "serviceStatus" IN ('ACTIVE', 'DRAINING', 'INACTIVE'));

-- A negative counter can only come from a decrement bug; fail loudly instead.
ALTER TABLE "spot_guard_services" ADD CONSTRAINT "spot_guard_services_counters_nonneg_check"
    CHECK ("consecutiveFailures" >= 0 AND "interruptionCount" >= 0
       AND "placementFailureCount" >= 0 AND "fallbackCount" >= 0 AND "restoreCount" >= 0);

ALTER TABLE "spot_guard_events" ADD CONSTRAINT "spot_guard_events_event_type_check"
    CHECK ("eventType" IN (
        'interruption', 'placement_failure', 'fallback_applied',
        'restore_attempted', 'restore_succeeded', 'restore_failed',
        'spot_enabled', 'spot_disabled', 'unmanaged',
        'capacity_transition', 'alb_predrain', 'governance_skip', 'backoff_skip'
    ));

ALTER TABLE "spot_guard_events" ADD CONSTRAINT "spot_guard_events_severity_check"
    CHECK ("severity" IN ('info', 'warning', 'critical'));

ALTER TABLE "spot_guard_events" ADD CONSTRAINT "spot_guard_events_from_capacity_check"
    CHECK ("fromCapacity" IS NULL OR "fromCapacity" IN ('spot', 'on_demand'));

ALTER TABLE "spot_guard_events" ADD CONSTRAINT "spot_guard_events_to_capacity_check"
    CHECK ("toCapacity" IS NULL OR "toCapacity" IN ('spot', 'on_demand'));

ALTER TABLE "spot_guard_task_sessions" ADD CONSTRAINT "spot_guard_task_sessions_capacity_type_check"
    CHECK ("capacityType" IN ('spot', 'on_demand'));

-- The reference implementation stored duration as a STRING and re-parsed it with
-- float(); enforcing non-negative numerics here makes that class of bug impossible.
ALTER TABLE "spot_guard_task_sessions" ADD CONSTRAINT "spot_guard_task_sessions_duration_check"
    CHECK ("durationSeconds" IS NULL OR "durationSeconds" >= 0);

-- An open session has no stoppedAt; a closed one must have it. Keeps the
-- open→closed state machine honest at the storage layer.
ALTER TABLE "spot_guard_task_sessions" ADD CONSTRAINT "spot_guard_task_sessions_open_consistency_check"
    CHECK (("isOpen" = true AND "stoppedAt" IS NULL) OR ("isOpen" = false AND "stoppedAt" IS NOT NULL));

ALTER TABLE "spot_guard_alert_dedup" ADD CONSTRAINT "spot_guard_alert_dedup_alert_type_check"
    CHECK ("alertType" IN (
        'interruption', 'placement_failure', 'remediation', 'fallback',
        'recovery', 'restore_attempt', 'restore_failed', 'spot_enabled', 'spot_disabled'
    ));

-- windowSeconds 0 means "never dedup" (user-initiated alerts always notify).
ALTER TABLE "spot_guard_alert_dedup" ADD CONSTRAINT "spot_guard_alert_dedup_window_check"
    CHECK ("windowSeconds" >= 0 AND "windowSeconds" <= 86400);

ALTER TABLE "spot_guard_actions" ADD CONSTRAINT "spot_guard_actions_action_check"
    CHECK ("action" IN ('fallback', 'restore', 'alb_predrain', 'enable_spot', 'disable_spot'));
