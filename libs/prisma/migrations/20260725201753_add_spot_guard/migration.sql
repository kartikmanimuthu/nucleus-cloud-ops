-- Fargate Spot Guard (SG-001) — initial schema
--
-- Ported from the standalone CDK/DynamoDB system (cdk-ecs-fargate-spot-automation).
-- Five new tables plus five additive columns on `accounts`.
--
-- ⚠️  HAND-AUTHORED — DO NOT REGENERATE THIS FILE WITH `prisma migrate dev`.
--
-- Two independent reasons:
--
--   1. Prisma 5 does not emit CHECK constraints, and every string enum in this
--      feature relies on one (house convention — see
--      20260713070000_agent_ops_check_constraints_new_values). The declared source
--      of truth for these value sets is the union types in
--      apps/web-ui/lib/db/repositories/spot-guard/interface.ts; keep them in sync.
--
--   2. More importantly, `prisma migrate dev` emits DESTRUCTIVE drift-correction
--      statements that have nothing to do with Spot Guard. The autogenerated diff
--      for this very change opened with "You are about to drop the column
--      `contentHash` on the `inventory_resources` table. All the data in the column
--      will be lost." and wanted to:
--          DROP INDEX "agent_memories_embedding_hnsw"
--          DROP INDEX "idx_inventory_search_vector"
--          DROP INDEX "idx_kb_document_chunks_embedding"
--          ALTER TABLE "inventory_resources" DROP COLUMN "contentHash"
--          ALTER TABLE "inventory_sync_status" ALTER COLUMN "errors" SET DEFAULT ...
--      Those three indexes were created by raw SQL in earlier migrations and cannot
--      be expressed in schema.prisma, so Prisma reads them as extraneous and drops
--      them. Applying that would silently destroy agent-memory vector search,
--      inventory full-text search, and a column of data. All five statements were
--      stripped; only the additive Spot Guard DDL below was kept.
--
--      (The underlying schema drift is pre-existing and unrelated to this feature.
--      It deserves its own fix — either by declaring those indexes in
--      schema.prisma where possible, or by documenting them as raw-SQL-managed.)
--
-- This migration is additive-only: no DROP, no RENAME, no ALTER COLUMN, no type
-- change to any pre-existing column. Every column added to `accounts` is nullable or
-- has a default, so it is backfill-free and every existing row is immediately valid.
--
-- WHY TIMESTAMPTZ(3) AND NOT TIMESTAMP(3)
-- Every timestamp here is TIMESTAMPTZ(3), which departs from the rest of this schema
-- (Prisma's DateTime default is timestamp(3), i.e. WITHOUT time zone). That default is
-- wrong for storing instants and it bit this feature during development:
--
--   '2026-07-20T00:00:00.000+05:30'::timestamp   -> 2026-07-20 00:00:00   (offset DISCARDED)
--   '2026-07-20T00:00:00.000+05:30'::timestamptz -> 2026-07-19 18:30:00+00 (correct instant)
--
-- node-postgres serialises a JS Date with the CLIENT's local offset, so a
-- timestamp-without-zone column stores local wall-clock rather than the instant. Writes
-- and reads stay self-consistent as long as every process shares one timezone — true on
-- ECS (TZ=UTC), false on a developer machine — which makes duration arithmetic
-- environment-dependent. These columns feed the Spot-vs-On-Demand hours report, whose
-- whole job is interval arithmetic, so correctness there is not optional. The bug
-- surfaced as six failing clipping tests on an IST machine and would have been invisible
-- in CI.
--
-- The rest of the schema has the same latent issue; fixing it is a separate change with
-- its own data-migration considerations and is deliberately not attempted here.
-- ═══════════════════════════════════════════════════════════════════════════════

-- ── AlterTable: additive Spot Guard columns on the existing accounts table ────
-- spotAutomationEnabled  drives the hub event-bus resource-policy allowlist.
-- spotAutomationStatus   is SEPARATE from connectionStatus on purpose: that column
--                        has two writers (web-ui validateAccount AND the workers
--                        discovery job, which derives it), so a Spot value written
--                        there would be clobbered by the next nightly scan. A
--                        customer who has not opted in is also not a broken
--                        connection and must not surface as an error.
